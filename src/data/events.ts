export function getRandomEvent(excludeId?: string): PartyEvent {
  const pool = excludeId ? PARTY_EVENTS.filter((e) => e.id !== excludeId) : PARTY_EVENTS;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex] || PARTY_EVENTS[0];
}
